package BaseCbb.RegCbb.gen

import BaseCbb.RegCbb._

/** C 头文件生成器（软件使用：基址 + 寄存器宏 + 字段 MASK/SHIFT/RST + 存储器宏） */
object CHeaderGen {

  def generate(map: RegFileMap): String = {
    val b = map.block
    val dev = b.devName.toUpperCase
    val guard = s"${dev}_REG_H"
    val sb = new StringBuilder
    sb ++= s"#ifndef $guard\n#define $guard\n\n"
    sb ++= s"/* ${b.name} Register Map - auto generated by RegCbb */\n\n"
    sb ++= s"#define ${dev}_REG_BASE ${hex(b.regBaseAddress)}\n"
    sb ++= s"#define ${dev}_MEM_BASE ${hex(b.memBaseAddress)}\n\n"

    sb ++= "/* ============ Registers ============ */\n"
    map.regs.foreach { a =>
      sb ++= s"/* ${a.reg.name} - ${a.reg.description} @ ${hex(a.byteOffset)} */\n"
      sb ++= s"#define ${dev}_${a.reg.name.toUpperCase}_REG (${dev}_REG_BASE + ${hex(a.byteOffset)})\n"
      a.fieldAllocations.foreach { fa =>
        val f = fa.field
        val mask: String =
          if (f.bitWidth >= 64) s"0x${((BigInt(1) << f.bitWidth) - 1).toString(16)}"
          else s"0x${(((BigInt(1) << f.bitWidth) - 1) << fa.bitOffset).toString(16)}"
        sb ++= s"#define ${dev}_${a.reg.name.toUpperCase}_${f.name.toUpperCase}_MASK  ${mask}\n"
        sb ++= s"#define ${dev}_${a.reg.name.toUpperCase}_${f.name.toUpperCase}_SHIFT ${fa.bitOffset}\n"
        if (f.resetValue != 0)
          sb ++= s"#define ${dev}_${a.reg.name.toUpperCase}_${f.name.toUpperCase}_RST  ${hex(f.resetValue)}\n"
      }
      sb ++= "\n"
    }

    if (map.mems.nonEmpty) {
      sb ++= "/* ============ Memories ============ */\n"
      map.mems.foreach { ma =>
        sb ++= s"/* ${ma.mem.name} - ${ma.mem.description} */\n"
        sb ++= s"#define ${dev}_${ma.mem.name.toUpperCase}_MEM   ${hex(ma.baseAddress)}\n"
        sb ++= s"#define ${dev}_${ma.mem.name.toUpperCase}_DEPTH ${ma.mem.depth}\n"
        sb ++= s"#define ${dev}_${ma.mem.name.toUpperCase}_WIDTH ${ma.mem.dataWidth}\n"
        sb ++= s"#define ${dev}_${ma.mem.name.toUpperCase}_SIZE  ${ma.mem.byteSize}\n\n"
      }
    }

    sb ++= s"#endif /* $guard */\n"
    sb.toString
  }

  private def hex(v: BigInt): String = s"0x${v.toString(16)}"
}
